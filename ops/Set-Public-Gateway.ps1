<#
.SYNOPSIS
Publishes the pool at https://<Hostname> through a Cloudflare Tunnel, behind the port's public
gateway (pools-rs serve-gateway: machine keys for inference, a key sign-in for the dashboard).
Safe to rerun.

.DESCRIPTION
Prerequisites: the domain is active in Cloudflare and 'cloudflared tunnel login'
has written %USERPROFILE%\.cloudflared\cert.pem for that zone.

1. Creates the named tunnel once (credentials in state\cloudflared\, which is
   ACL-restricted and backed up with state\) and points <Hostname> at it with
   a proxied CNAME.
2. Writes state\cloudflared\config.yml: <Hostname> -> 127.0.0.1:<Port>, every
   other hostname 404, and install.json's publicGateway.
3. Registers "<TaskPrefix> - public gateway" and "<TaskPrefix> - cloudflare tunnel"
   (deploy\common.ps1's Set-PoolRsTask, on pool-rs.json's current version), enables and
   restarts both and checks the gateway answers locally.

-Hostname, -TunnelName and -Port default to install.json's publicGateway. -Remove stops and
deletes both tasks; the DNS route is left for you to delete in Cloudflare, and the tunnel itself
stays until 'cloudflared tunnel delete'. -Root is the install (default: the live one).
#>
[CmdletBinding()]
param(
  [string]$Hostname,
  [string]$TunnelName,
  [ValidateRange(0, 65535)][int]$Port = 0,
  [switch]$Remove,
  [string]$Root,
  [string]$TaskPrefix = 'Agent Pools (rs)'
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '..\deploy\common.ps1')
if (-not $Root) { $Root = $script:LiveRoot }
$poolRoot = (Resolve-Path -LiteralPath $Root).ProviderPath.TrimEnd('\')
$live = $poolRoot -ieq $script:LiveRoot.TrimEnd('\')
$installPath = Join-Path $poolRoot 'state\install.json'
$install = Get-Content -LiteralPath $installPath -Raw | ConvertFrom-Json
if (-not $Hostname) { $Hostname = $install.publicGateway.hostname }
if (-not $Hostname) { throw 'Pass -Hostname (install.json has no publicGateway.hostname yet).' }
if (-not $TunnelName) { $TunnelName = if ($install.publicGateway.tunnel) { $install.publicGateway.tunnel } else { 'agentpools' } }
if (-not $Port) { $Port = if ($install.publicGateway.port) { [int]$install.publicGateway.port } else { 8330 } }
if ($Port -lt 1024) { throw "Port $Port is below 1024" }
$cloudflared = Join-Path $env:LOCALAPPDATA 'Programs\cloudflared\cloudflared.exe'
$cfDir = Join-Path $poolRoot 'state\cloudflared'
$tasks = Get-PoolRsTasks $TaskPrefix | Where-Object { $_.Key -in 'gateway', 'tunnel' }
$gatewayTask = ($tasks | Where-Object Key -eq 'gateway').Name
$tunnelTask = ($tasks | Where-Object Key -eq 'tunnel').Name

if ($Remove) {
  foreach ($t in $tunnelTask, $gatewayTask) {
    if (Get-ScheduledTask -TaskName $t -ErrorAction SilentlyContinue) {
      Stop-ScheduledTask -TaskName $t
      Unregister-ScheduledTask -TaskName $t -Confirm:$false
      Write-Output "Removed task '$t'."
    }
  }
  Write-Output "Delete the $Hostname DNS record in Cloudflare, and the tunnel with: cloudflared tunnel delete $TunnelName"
  return
}

if (-not (Test-Path -LiteralPath $cloudflared)) { throw "cloudflared not found at $cloudflared" }
if (-not (Test-Path -LiteralPath (Join-Path $env:USERPROFILE '.cloudflared\cert.pem'))) { throw "Run 'cloudflared tunnel login' first and pick the zone for $Hostname." }
New-Item -ItemType Directory -Force -Path $cfDir | Out-Null

# 1. Tunnel and DNS route.
$tunnels = (& $cloudflared tunnel list --output json --name $TunnelName) -join "`n" | ConvertFrom-Json
if ($LASTEXITCODE -ne 0) { throw 'cloudflared tunnel list failed.' }
# A live tunnel reports deleted_at as the zero time, not null.
$tunnel = @($tunnels | Where-Object { $_.name -eq $TunnelName -and (-not $_.deleted_at -or ([datetime]$_.deleted_at).Year -le 1) }) | Select-Object -First 1
if (-not $tunnel) {
  $credPending = Join-Path $cfDir 'pending.json'
  & $cloudflared tunnel create --credentials-file $credPending $TunnelName | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'cloudflared tunnel create failed.' }
  $tunnel = @((& $cloudflared tunnel list --output json --name $TunnelName) -join "`n" | ConvertFrom-Json) | Select-Object -First 1
  Move-Item -LiteralPath $credPending -Destination (Join-Path $cfDir "$($tunnel.id).json") -Force
  Write-Output "Created tunnel $TunnelName ($($tunnel.id))."
}
$credentials = Join-Path $cfDir "$($tunnel.id).json"
if (-not (Test-Path -LiteralPath $credentials)) { throw "Tunnel $TunnelName exists but its credentials file $credentials is missing; delete the tunnel in Cloudflare and rerun." }
& $cloudflared tunnel route dns --overwrite-dns $tunnel.id $Hostname
if ($LASTEXITCODE -ne 0) { throw "cloudflared tunnel route dns failed for $Hostname." }

# 2. Config: one public hostname, everything else refused at the connector.
$config = @"
# Generated by ops\Set-Public-Gateway.ps1. $Hostname -> pools-rs serve-gateway.
tunnel: $($tunnel.id)
credentials-file: $($credentials -replace '\\', '/')
no-autoupdate: true
loglevel: info
logfile: $((Join-Path $poolRoot 'logs\cloudflared.log') -replace '\\', '/')
ingress:
  - hostname: $Hostname
    service: http://127.0.0.1:$Port
    originRequest:
      connectTimeout: 10s
      noHappyEyeballs: true
  - service: http_status:404
"@
[IO.File]::WriteAllText((Join-Path $cfDir 'config.yml'), $config, [Text.UTF8Encoding]::new($false))
& $cloudflared tunnel --config (Join-Path $cfDir 'config.yml') ingress validate
if ($LASTEXITCODE -ne 0) { throw 'Tunnel ingress config is invalid.' }

# Gateway settings live in install.json so the service and docs agree.
$install | Add-Member -NotePropertyName publicGateway -NotePropertyValue ([pscustomobject]@{ hostname = $Hostname; port = $Port; tunnel = $TunnelName }) -Force
$tmp = "$installPath.$PID.tmp"
[IO.File]::WriteAllText($tmp, ($install | ConvertTo-Json -Depth 20), [Text.UTF8Encoding]::new($false))
Move-Item -LiteralPath $tmp -Destination $installPath -Force

# 3. The port's tasks: logon plus a 5-minute keepalive, IgnoreNew, at normal priority (the
# default, below normal, lets a busy CPU starve cloudflared's connections).
$version = (Read-Json (Join-Path $poolRoot 'pool-rs\pool-rs.json')).current
if (-not $version) { throw 'pool-rs\pool-rs.json has no current version; run deploy\Install-Pool-Rs.ps1 first.' }
foreach ($task in $tasks) {
  Set-PoolRsTask $poolRoot $version $task $live | Write-Output
  Enable-ScheduledTask -TaskName $task.Name | Out-Null
}
Stop-ScheduledTask -TaskName $gatewayTask -ErrorAction SilentlyContinue
Start-ScheduledTask -TaskName $gatewayTask
Stop-ScheduledTask -TaskName $tunnelTask -ErrorAction SilentlyContinue
# Stopping the task leaves its cloudflared running; end it so the new config loads.
$cfConfig = Join-Path $cfDir 'config.yml'
Get-CimInstance Win32_Process -Filter "Name='cloudflared.exe'" | Where-Object { $_.CommandLine -and $_.CommandLine.IndexOf($cfConfig, [StringComparison]::OrdinalIgnoreCase) -ge 0 } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force }
Start-ScheduledTask -TaskName $tunnelTask

$deadline = [DateTime]::UtcNow.AddSeconds(120)
$status = 0
do {
  Start-Sleep -Milliseconds 500
  # Any other Host gets the gateway's own 404, which proves it is listening.
  try { $status = [int](Invoke-WebRequest "http://127.0.0.1:$Port/" -UseBasicParsing -TimeoutSec 5).StatusCode }
  catch { if ($_.Exception.Response) { $status = [int]$_.Exception.Response.StatusCode } }
} while ($status -ne 404 -and [DateTime]::UtcNow -lt $deadline)
if ($status -ne 404) { throw "The gateway did not answer on 127.0.0.1:$Port; see logs\public-gateway-events.jsonl." }
Write-Output "Gateway answering on 127.0.0.1:$Port; tunnel task started. Public URL: https://$Hostname"
